#!/usr/bin/env bash
#
# Generate src/UNO_R4_Health_Checker/ApiVersion.h from the API version in
# src/UNO_R4_Health_Checker/.version.
#
# The Arduino build copies only source files into its build folder, so the
# firmware cannot include .version directly. tools/build.sh runs this script
# before every build. After changing .version, run it by hand before building
# with the Arduino IDE, and commit the regenerated header.
#
# Usage:
#   tools/generate_api_version.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKETCH="$ROOT/src/UNO_R4_Health_Checker"
VERSION_FILE="$SKETCH/.version"
HEADER="$SKETCH/ApiVersion.h"

if [[ ! -f "$VERSION_FILE" ]]; then
  echo "error: $VERSION_FILE not found" >&2
  exit 1
fi

VERSION="$(tr -d '[:space:]' < "$VERSION_FILE")"

if [[ ! "$VERSION" =~ ^[1-9][0-9]{0,3}$ ]]; then
  echo "error: $VERSION_FILE must contain a positive integer up to 9999, found '$VERSION'" >&2
  exit 1
fi

CONTENT="#ifndef API_VERSION_H
#define API_VERSION_H

// Generated by tools/generate_api_version.sh from .version. Do not edit.
//
// API version. Every endpoint is served under /api/v<API_VERSION>/.
constexpr unsigned API_VERSION = ${VERSION};

#endif"

# Rewrite only on a change, so the build is not invalidated needlessly.
if [[ ! -f "$HEADER" ]] || [[ "$(cat "$HEADER")" != "$CONTENT" ]]; then
  printf '%s\n' "$CONTENT" > "$HEADER"
  echo "Generated ApiVersion.h for API version $VERSION"
fi
